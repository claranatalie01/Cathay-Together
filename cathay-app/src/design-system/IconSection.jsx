// Several tokens can share one value. Show the icon token if there is one, else the first, plus a count.
function tokenLabel(token) {
  if (!token) return 'not a token';
  const names = token.split(', ');
  const main = names.find((n) => n.startsWith('--color-icon')) || names[0];
  return names.length > 1 ? `${main} (+${names.length - 1} same value)` : main;
}

function Colour({ colour }) {
  return (
    <li className="ds-icon__colour">
      <span
        className="ds-icon__dot"
        style={{ background: colour.hex }}
        aria-hidden="true"
      />
      <code>{colour.hex}</code>
      <span className="ds-icon__token">{tokenLabel(colour.token)}</span>
    </li>
  );
}

function IconCard({ icon }) {
  return (
    <li className="ds-icon">
      <span className="ds-icon__tile">
        <img src={`/assets/${icon.file}`} alt="" />
      </span>
      <code className="ds-icon__file">{icon.file}</code>
      <span className="ds-icon__meta">
        {icon.width} x {icon.height}
        {icon.strokeWidths.length > 0 && `, stroke ${icon.strokeWidths.join(' / ')}`}
      </span>
      <ul className="ds-icon__colours">
        {icon.colours.map((c) => (
          <Colour colour={c} key={c.hex} />
        ))}
      </ul>
      {icon.roles.map((role) => (
        <span className="ds-icon__role" key={role}>
          {role}
        </span>
      ))}
      {icon.usedIn.length > 0 && <span className="ds-icon__used">{icon.usedIn.join(', ')}</span>}
    </li>
  );
}

export default function IconSection() {
  const used = ICONS.filter((icon) => icon.usedIn.length > 0);
  const unused = ICONS.filter((icon) => icon.usedIn.length === 0);
  return (
    <section className="ds-section" aria-labelledby="ds-icons">
      <h2 className="ds-section__title" id="ds-icons">
        Icons and vectors
      </h2>
      <p className="ds-section__text">
        {ICONS.length} SVG files in <code>public/assets</code> (plus {OTHER_ASSETS.length} photos and raster images). They are
        retained exactly as they are: no file is replaced, redrawn, recoloured or removed here. Colours are written inside
        each file, so <code>--color-icon-default</code> and <code>--color-icon-brand</code> do not recolour them. This list
        is generated by <code>npm run icons:inventory</code>, so it cannot drift from the files.
      </p>

      <div className="ds-group">
        <h3 className="ds-group__title">In use ({used.length})</h3>
        <ul className="ds-icons">
          {used.map((icon) => (
            <IconCard icon={icon} key={icon.file} />
          ))}
        </ul>
      </div>

      <div className="ds-group">
        <h3 className="ds-group__title">Not referenced anywhere in src ({unused.length})</h3>
        <p className="ds-section__text">
          Present in the folder (for screens that are not built yet, or leftovers from the Figma export). Nothing is
          removed.
        </p>
        <ul className="ds-icons">
          {unused.map((icon) => (
            <IconCard icon={icon} key={icon.file} />
          ))}
        </ul>
      </div>

      <div className="ds-group">
        <h3 className="ds-group__title">Bottom nav compared with the real app (note only)</h3>
        <table className="ds-table">
          <thead>
            <tr>
              <th scope="col">Item</th>
              <th scope="col">Our files and layout</th>
              <th scope="col">Real app</th>
              <th scope="col">Confidence</th>
            </tr>
          </thead>
          <tbody>
            {NAV_NOTES.map(([item, ours, real, confidence]) => (
              <tr key={item}>
                <th scope="row">{item}</th>
                <td>{ours}</td>
                <td>{real}</td>
                <td>{confidence}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}
