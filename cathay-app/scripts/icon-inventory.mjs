#!/usr/bin/env node
// Builds src/design-system/iconInventory.js from the real files in public/assets.
// Read-only for the icons: it never edits an SVG. Run: npm run icons:inventory
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = join(root, 'public', 'assets');
const src = join(root, 'src');

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

// Where each file is used (any .js/.jsx in src that mentions the file name).
const code = walk(src).filter((f) => /\.(jsx?|css)$/.test(f) && !f.includes('iconInventory'));
const sources = code.map((f) => [relative(root, f), readFileSync(f, 'utf8')]);

// Hex values in tokens.css :root (first block only), to say whether a colour is a token.
const tokenCss = readFileSync(join(src, 'styles', 'tokens.css'), 'utf8').split('Design system v2.0')[0];
const tokenByHex = {};
for (const m of tokenCss.matchAll(/(--color-[\w-]+)\s*:\s*(#[0-9a-fA-F]{6})/g)) {
  (tokenByHex[m[2].toLowerCase()] ||= []).push(m[1]);
}

// Nav roles come from nav.js so the inventory names them correctly.
const nav = readFileSync(join(src, 'data', 'nav.js'), 'utf8');
const navRole = {};
for (const block of nav.matchAll(/(\w+):\s*\{\s*active:\s*'(\w+)',\s*icons:\s*\{([^}]*)\}/g)) {
  for (const m of block[3].matchAll(/(\w+):\s*'([\w-]+\.svg)'/g)) {
    const tab = { home: 'Home', book: 'Book', trips: 'My Trips', profile: 'Profile', groups: 'Travel Groups' }[m[1]];
    const active = block[2] === m[1];
    (navRole[m[2]] ||= new Set()).add(`Bottom nav: ${tab} (${active ? 'active' : 'inactive'})`);
  }
}

// v2.0 nav icons (NAV_ICONS_V2 in nav.js).
for (const m of nav.matchAll(/(\w+):\s*\{\s*off:\s*'([\w-]+\.svg)',\s*on:\s*'([\w-]+\.svg)'\s*\}/g)) {
  const tab = { home: 'Home', book: 'Book', trips: 'My trips', profile: 'Profile', groups: 'Travel Groups' }[m[1]];
  (navRole[m[2]] ||= new Set()).add(`Bottom nav v2: ${tab} (inactive)`);
  (navRole[m[3]] ||= new Set()).add(`Bottom nav v2: ${tab} (active)`);
}

const files = readdirSync(assets).sort();
const svgs = files.filter((f) => f.endsWith('.svg'));
const icons = svgs.map((file) => {
  const text = readFileSync(join(assets, file), 'utf8');
  const root = text.match(/<svg[^>]*>/)?.[0] ?? '';
  const attr = (name) => root.match(new RegExp(`${name}="([^"]*)"`))?.[1] ?? '';
  const colours = [...new Set([...text.matchAll(/(?:stroke|fill)="(#[0-9a-fA-F]{3,8}|white|black)"/g)].map((m) => m[1].toLowerCase()))];
  const strokeWidths = [...new Set([...text.matchAll(/stroke-width="([\d.]+)"/g)].map((m) => m[1]))];
  const usedIn = sources.filter(([, body]) => body.includes(file.replace('.svg', ''))).map(([p]) => p);
  return {
    file,
    width: attr('width'),
    height: attr('height'),
    colours: colours.map((c) => ({ hex: c, token: (tokenByHex[c] || []).join(', ') })),
    strokeWidths,
    roles: [...(navRole[file] || [])],
    usedIn,
  };
});

const other = files.filter((f) => !f.endsWith('.svg'));
const out = `// GENERATED by scripts/icon-inventory.mjs from public/assets. Do not edit by hand.
// The SVG files are never changed by this script.
export const ICONS = ${JSON.stringify(icons, null, 2)};
export const OTHER_ASSETS = ${JSON.stringify(other)};
`;
writeFileSync(join(src, 'design-system', 'iconInventory.js'), out);
console.log(`Icon inventory: ${icons.length} SVG files, ${other.length} other images.`);
